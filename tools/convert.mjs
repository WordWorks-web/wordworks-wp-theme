const utilities = new Map(); // style string -> class name
function utilityClass( style ) {
	const norm = style.split( ';' ).map( ( s ) => s.trim() ).filter( Boolean ).join( ';' );
	if ( ! norm ) return '';
	if ( ! utilities.has( norm ) ) {
		const name = 'u-' + norm.replace( /[^a-z0-9]+/gi, '-' ).replace( /^-|-$/g, '' ).toLowerCase().slice( 0, 40 ) + '-' + utilities.size;
		utilities.set( norm, name );
	}
	return utilities.get( norm );
}
function utilitiesCss() {
	let css = '/* Generated by tools/convert.mjs from inline styles in the design. Do not edit. */\n';
	for ( const [ style, name ] of utilities ) {
		const decl = style.split( ';' ).map( ( d ) => d.trim() ).filter( Boolean ).map( ( d ) => d + ' !important' ).join( ';' );
		css += `.${ name }{${ decl }}\n`;
	}
	return css;
}

/* --------------------------------------------------------------- helpers */

const INLINE = new Set( [ 'a', 'span', 'strong', 'em', 'b', 'i', 'cite', 'br', 'mark', 'small', 'code', 'sup', 'sub', 'abbr', 'u', 's' ] );

function classesOf( el, drop = [] ) {
	const list = ( el.getAttribute( 'class' ) || '' ).split( /\s+/ ).filter( ( c ) => c && ! drop.includes( c ) );
	const style = el.getAttribute( 'style' );
	if ( style ) list.push( utilityClass( style ) );
	return list.join( ' ' ) || undefined;
}

function mapHref( href ) {
	if ( ! href ) return href;
	const m = href.match( /^([A-Za-z]+\.dc\.html)(#.*)?$/ );
	if ( m ) {
		const key = LINK[ m[ 1 ] ];
		return `__WWURL:${ key }__` + ( m[ 2 ] || '' );
	}
	return href;
}

/** Serialize inline content, converting design-only spans to editor formats. */
function inlineHTML( nodes ) {
	let out = '';
	const list = Array.from( nodes );
	list.forEach( ( n, i ) => {
		if ( n.nodeType === 3 ) {
			out += escapeText( n.textContent );
			return;
		}
		if ( n.nodeType !== 1 ) return;
		const tag = n.tagName.toLowerCase();
		const cls = n.getAttribute( 'class' ) || '';
		if ( tag === 'span' ) {
			const parts = cls.split( /\s+/ );
			let inner = inlineHTML( n.childNodes );
			if ( parts.includes( 'accent' ) ) inner = `<mark style="background-color:rgba(0, 0, 0, 0)" class="has-inline-color has-primary-color">${ inner }</mark>`;
			if ( parts.includes( 'w' ) ) inner = `<mark style="background-color:rgba(0, 0, 0, 0)" class="has-inline-color has-light-color">${ inner }</mark>`;
			out += inner;
			if ( parts.includes( 'st-block' ) && list.slice( i + 1 ).some( ( x ) => x.nodeType === 1 || x.textContent.trim() ) ) out += '<br>';
			return;
		}
		if ( tag === 'br' ) {
			out += '<br>';
			return;
		}
		if ( tag === 'a' ) {
			const href = mapHref( n.getAttribute( 'href' ) );
			const c = cls ? ` class="${ cls }"` : '';
			out += `<a href="${ href }"${ c }>${ inlineHTML( n.childNodes ) }</a>`;
			return;
		}
		const c = cls ? ` class="${ cls }"` : '';
		out += `<${ tag }${ c }>${ inlineHTML( n.childNodes ) }</${ tag }>`;
	} );
	return out;
}
function escapeText( t ) {
	return t.replace( /&/g, '&amp;' ).replace( /</g, '&lt;' ).replace( />/g, '&gt;' ).replace( /\s+/g, ' ' );
}
const trimHTML = ( h ) => h.replace( /^\s+|\s+$/g, '' );

/* ----------------------------------------------------------- converter */

class PageConverter {
	constructor( page ) {
		this.page = page;
		this.images = {}; // placeholder id -> { file, kind, search, fallback }
	}

	nextImageId() {
		PageConverter.counter = ( PageConverter.counter || 900000 ) + 1;
		return PageConverter.counter;
	}

	children( el ) {
		const blocks = [];
		let run = [];
		const flush = () => {
			const html = trimHTML( inlineHTML( run ) );
			if ( html ) blocks.push( createBlock( 'core/paragraph', { content: html } ) );
			run = [];
		};
		for ( const n of Array.from( el.childNodes ) ) {
			if ( n.nodeType === 3 ) {
				if ( n.textContent.trim() ) run.push( n );
				continue;
			}
			if ( n.nodeType !== 1 ) continue;
			const tag = n.tagName.toLowerCase();
			const isBtn = tag === 'a' && /\bbtn\b/.test( n.getAttribute( 'class' ) || '' );
			if ( INLINE.has( tag ) && ! isBtn && ! ( tag === 'span' && n.classList.contains( 'ph-label' ) ) ) {
				if ( el.classList && el.classList.contains( 'stat' ) ) {
					flush();
					blocks.push( createBlock( 'core/paragraph', { content: inlineHTML( [ n ] ), className: tag === 'span' ? 'stat-l' : 'stat-n' } ) );
					continue;
				}
				if ( tag === 'br' && ! run.length ) continue;
				run.push( n );
				continue;
			}
			flush();
			blocks.push( ...this.block( n ) );
		}
		flush();
		return blocks;
	}

	block( el ) {
		const tag = el.tagName.toLowerCase();
		const cls = el.getAttribute( 'class' ) || '';
		const cl = el.classList;
		const anchor = el.getAttribute( 'id' ) || undefined;

		if ( tag === 'span' && cl.contains( 'ph-label' ) ) return [];
		if ( /^h[1-6]$/.test( tag ) ) {
			return [ createBlock( 'core/heading', { level: +tag[ 1 ], content: trimHTML( inlineHTML( el.childNodes ) ), className: classesOf( el ), anchor } ) ];
		}
		if ( tag === 'p' ) {
			return [ createBlock( 'core/paragraph', { content: trimHTML( inlineHTML( el.childNodes ) ), className: classesOf( el ), anchor } ) ];
		}
		if ( tag === 'ul' || tag === 'ol' ) {
			const items = Array.from( el.children ).filter( ( c ) => c.tagName.toLowerCase() === 'li' ).map( ( li ) => {
				const nested = Array.from( li.children ).filter( ( c ) => /^(ul|ol)$/i.test( c.tagName ) );
				const inline = Array.from( li.childNodes ).filter( ( c ) => ! nested.includes( c ) );
				return createBlock( 'core/list-item', { content: trimHTML( inlineHTML( inline ) ), className: classesOf( li ) }, nested.flatMap( ( n ) => this.block( n ) ) );
			} );
			return [ createBlock( 'core/list', { ordered: tag === 'ol', className: classesOf( el ), anchor }, items ) ];
		}
		if ( tag === 'a' && cl.contains( 'btn' ) ) {
			const wrapCls = classesOf( el, [ 'btn', 'btn-sm' ] );
			const btnCls = cl.contains( 'btn-sm' ) ? 'btn-sm' : undefined;
			return [ createBlock( 'core/buttons', { className: wrapCls }, [ createBlock( 'core/button', { text: trimHTML( inlineHTML( el.childNodes ) ), url: mapHref( el.getAttribute( 'href' ) ), className: btnCls } ) ] ) ];
		}
		if ( tag === 'svg' ) {
			return [ createBlock( 'core/html', { content: el.outerHTML.replace( /<path([^>]*)><\/path>/g, '<path$1/>' ) } ) ];
		}
		if ( tag === 'form' ) {
			const type = this.page.key === 'contacto' ? 'contacto' : 'trabaja';
			return [ createBlock( 'core/shortcode', { text: `[wordworks_form type="${ type }"]` } ) ];
		}
		if ( tag === 'div' && /\b(iph|img-ph|client-logo)\b/.test( cls ) ) {
			return [ this.image( el ) ];
		}
		if ( tag === 'section' && cl.contains( 'photo' ) ) {
			return [ this.cover( el ) ];
		}
		if ( tag === 'nav' && cl.contains( 'pager' ) ) return [];

		// Structural element -> Group, keeping its tag and classes.
		const tagName = [ 'section', 'article', 'aside', 'header', 'footer', 'main', 'nav', 'figure', 'figcaption', 'blockquote' ].includes( tag ) ? tag : 'div';
		return [ createBlock( 'core/group', { tagName, className: classesOf( el ), anchor }, this.children( el ) ) ];
	}

	cover( el ) {
		const label = el.querySelector( ':scope > .ph-label' );
		const m = label && label.textContent.match( /\(([^()]+\.(?:png|jpe?g|webp|gif))\)|(?:Foto|Fondo|Hero):\s*([^\s(]+\.(?:png|jpe?g|webp|gif))/i );
		const file = m ? ( m[ 1 ] || m[ 2 ] ) : null;
		const attrs = { dimRatio: 0, isDark: true, tagName: 'section', className: classesOf( el ), anchor: el.getAttribute( 'id' ) || undefined };
		if ( file ) {
			const id = this.nextImageId();
			attrs.url = 'https://media.wordworks.invalid/' + id;
			attrs.id = id;
			attrs.alt = '';
			this.images[ id ] = { file, kind: 'cover', label: label.textContent.trim() };
		}
		return createBlock( 'core/cover', attrs, this.children( el ) );
	}

	image( el ) {
		const text = el.textContent.trim();
		const m = text.match( /\(([^()]+\.(?:png|jpe?g|webp|gif|svg))\)/i );
		const named = NAMED_IMAGES[ text ];
		const file = m ? m[ 1 ] : named ? named.file : text.toLowerCase().replace( /[^a-z0-9]+/g, '-' );
		const alt = ( m ? text.replace( m[ 0 ], '' ) : text ).replace( /^[^:]+:\s*/, '' ).replace( /,\s*\d+×\d+$/, '' ).trim();
		const id = this.nextImageId();
		const style = el.getAttribute( 'style' ) || '';
		const ar = ( style.match( /aspect-ratio:\s*([\d/ .]+)/ ) || [] )[ 1 ];
		const rest = style.replace( /aspect-ratio:[^;]+;?/, '' );
		const kind = cl( el, 'client-logo' ) ? 'logo-img client-logo-img' : cl( el, 'img-ph' ) ? 'logo-img' : 'ph-img';
		const className = [ kind, rest ? utilityClass( rest ) : '' ].filter( Boolean ).join( ' ' );
		const fallback = serialize( createBlock( 'core/group', { className: classesOf( el ) }, [ createBlock( 'core/paragraph', { content: escapeText( text ) } ) ] ) );
		this.images[ id ] = { file, kind: 'image', label: text, search: named ? named.search : undefined, fallback };
		return createBlock( 'core/image', {
			id,
			url: 'https://media.wordworks.invalid/' + id,
			alt,
			sizeSlug: 'full',
			linkDestination: 'none',
			aspectRatio: ar ? ar.replace( /\s/g, '' ) : undefined,
			scale: kind === 'ph-img' ? 'cover' : 'contain',
			className,
		} );
	}
}
const cl = ( el, c ) => el.classList.contains( c );

/* ----------------------------------------------------------------- write */

function phpString( s ) {
	return "'" + s.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) + "'";
}

function patternFile( { title, slug, categories, keywords, description, markup, images, inserter = true, viewport = 1440 } ) {
	const imgs = Object.entries( images ).map( ( [ id, i ] ) =>
		`\t${ id } => array( 'file' => ${ phpString( i.file ) }, 'kind' => '${ i.kind }'` + ( i.fallback ? `, 'fallback' => ${ phpString( i.fallback ) }` : '' ) + ' ),'
	).join( '\n' );
	return `<?php
/**
 * Title: ${ title }
 * Slug: ${ slug }
 * Categories: ${ categories }
 * Keywords: ${ keywords }
 * Description: ${ description }
 * Viewport Width: ${ viewport }
 * Inserter: ${ inserter ? 'yes' : 'no' }
 *
 * Generated by tools/convert.mjs from design/. Re-run the converter instead of editing by hand.
 *
 * @package wordworks
 */

$wordworks_images = array(
${ imgs }
);

echo wordworks_render( // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
	<<<'WORDWORKS_MARKUP'
${ markup }
WORDWORKS_MARKUP
	,
	$wordworks_images
);
`;
}

function loadDoc( file ) {
	const html = fs.readFileSync( path.join( DESIGN, file + '.dc.html' ), 'utf8' );
	const doc = new window.DOMParser().parseFromString( html, 'text/html' );
	return doc;
}

const manifest = { pages: [], images: {} };
fs.mkdirSync( path.join( THEME, 'patterns' ), { recursive: true } );

for ( const page of PAGES ) {
	const doc = loadDoc( page.file );
	const main = doc.querySelector( 'main' );
	const conv = new PageConverter( page );
	let sections = Array.from( main.children );
	if ( page.posts ) sections = []; // The blog page is the posts page (templates/home.html).
	const blocks = sections.flatMap( ( s ) => conv.block( s ) );
	const markup = serialize( blocks );
	if ( ! page.posts ) {
		fs.writeFileSync(
			path.join( THEME, 'patterns', `page-${ page.key }.php` ),
			patternFile( {
				title: `Página: ${ page.title }`,
				slug: `wordworks/page-${ page.key }`,
				categories: 'wordworks-pages',
				keywords: `${ page.title }, página, word works`,
				description: `Contenido completo de la página «${ page.title }» de wordworks.es.`,
				markup,
				images: conv.images,
			} )
		);
	}
	manifest.pages.push( {
		key: page.key,
		title: page.title,
		slug: page.slug ?? page.key,
		template: page.solid ? 'page-solid-header' : '',
		pattern: page.posts ? null : `wordworks/page-${ page.key }`,
		posts_page: !! page.posts,
		front_page: page.key === 'home',
		section: page.section || null,
	} );
	for ( const [ id, img ] of Object.entries( conv.images ) ) {
		const entry = manifest.images[ img.file ] ||= { file: img.file, search: img.search || null, pages: [], labels: [] };
		if ( ! entry.pages.includes( page.key ) ) entry.pages.push( page.key );
		if ( ! entry.labels.includes( img.label ) ) entry.labels.push( img.label );
	}
}

/* Footer pattern from the home page's footer. */
